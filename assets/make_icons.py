#!/usr/bin/env python3
"""Render assets/icon.svg into everything the builds need. Needs rsvg-convert and Pillow; the results are committed, so
building the program does not need either.

  assets/icons/hicolor/<n>x<n>/apps/exceeded.png   Linux (make install)
  assets/exceeded.ico                              Windows (the program's icon, via windres)
  assets/exceeded.icns                             macOS (the app bundle)
  src/appicon.c                                    the window icon: a 128x128 RGBA image, deflate-compressed
"""
import io, os, subprocess, zlib
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..')
svg = os.path.join(here, 'icon.svg')

def render(n):
    png = subprocess.run(['rsvg-convert', '-w', str(n), '-h', str(n), svg], check=True, capture_output=True).stdout
    return Image.open(io.BytesIO(png)).convert('RGBA')

sizes = [16, 24, 32, 48, 64, 128, 256, 512]
img = {n: render(n) for n in sizes}

for n in (16, 24, 32, 48, 64, 128, 256, 512):
    d = os.path.join(here, 'icons', 'hicolor', '%dx%d' % (n, n), 'apps')
    os.makedirs(d, exist_ok=True)
    img[n].save(os.path.join(d, 'exceeded.png'), optimize=True)
sc = os.path.join(here, 'icons', 'hicolor', 'scalable', 'apps')
os.makedirs(sc, exist_ok=True)
open(os.path.join(sc, 'exceeded.svg'), 'wb').write(open(svg, 'rb').read())

img[256].save(os.path.join(here, 'exceeded.ico'), format='ICO', sizes=[(n, n) for n in (16, 24, 32, 48, 64, 128, 256)], append_images=[])
big = render(1024)
big.save(os.path.join(here, 'exceeded.icns'), format='ICNS')

raw = img[128].tobytes()
z = zlib.compress(raw, 9)
with open(os.path.join(root, 'src', 'appicon.c'), 'w') as f:
    f.write('/* appicon.c - the window icon, generated by assets/make_icons.py from assets/icon.svg: 128x128 RGBA, deflate-compressed */\n')
    f.write('#include "appicon.h"\n\n')
    f.write('const int APPICON_WIDTH = 128, APPICON_HEIGHT = 128;\nconst unsigned long APPICON_RAW = %d;\n' % len(raw))
    f.write('const unsigned long APPICON_ZLEN = %d;\nconst unsigned char APPICON_Z[%d] = {\n' % (len(z), len(z)))
    for i in range(0, len(z), 16):
        f.write('    ' + ', '.join('0x%02x' % b for b in z[i:i + 16]) + ',\n')
    f.write('};\n')
print('ok', len(z), 'bytes of icon data')
